/// User domain model representing an authenticated user.
/// 
/// This model represents a user in the domain layer and is independent
/// of any data source implementation. It uses freezed for immutability
/// and json_serializable for efficient JSON parsing.
library;

import 'package:freezed_annotation/freezed_annotation.dart';

part 'user_model.freezed.dart';
part 'user_model.g.dart';

/// User domain model.
/// 
/// Contains user information including authentication details,
/// profile data, and metadata. This model is used throughout
/// the application to represent user entities.
@freezed
class UserModel with _$UserModel {
  const factory UserModel({
    /// Unique user identifier from Supabase auth
    required String id,

    /// User's email address
    required String email,

    /// User's display name (optional)
    String? displayName,

    /// Profile image URL (optional)
    String? avatarUrl,

    /// User's phone number (optional)
    String? phoneNumber,

    /// Indicates if the user is anonymous
    @Default(false) bool isAnonymous,

    /// Account creation timestamp
    required DateTime createdAt,

    /// Last sign-in timestamp
    DateTime? lastSignInAt,

    /// User's subscription tier (free, premium, etc.)
    @Default('free') String subscriptionTier,

    /// Additional metadata as key-value pairs
    @Default({}) Map<String, dynamic> metadata,
  }) = _UserModel;

  /// Creates a UserModel from JSON.
  /// 
  /// This factory method is generated by json_serializable
  /// and handles deserialization from JSON to the model.
  factory UserModel.fromJson(Map<String, dynamic> json) =>
      _$UserModelFromJson(json);

  /// Creates a UserModel from Supabase User object.
  /// 
  /// This factory method converts a Supabase auth User to our
  /// domain model, abstracting the data source implementation.
  factory UserModel.fromSupabaseUser(dynamic supabaseUser) {
    return UserModel(
      id: supabaseUser.id,
      email: supabaseUser.email ?? '',
      displayName: supabaseUser.userMetadata?['display_name'],
      avatarUrl: supabaseUser.userMetadata?['avatar_url'],
      phoneNumber: supabaseUser.phone,
      isAnonymous: supabaseUser.isAnonymous ?? false,
      createdAt: DateTime.parse(supabaseUser.createdAt),
      lastSignInAt: supabaseUser.lastSignInAt != null
          ? DateTime.parse(supabaseUser.lastSignInAt)
          : null,
      subscriptionTier:
          supabaseUser.userMetadata?['subscription_tier'] ?? 'free',
      metadata: supabaseUser.userMetadata ?? {},
    );
  }
}
